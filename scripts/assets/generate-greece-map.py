"""Build the lesson's local coastline from Natural Earth's public-domain land data.

Usage: python scripts/assets/generate-greece-map.py path/to/ne_50m_land.zip
Source: https://naciscdn.org/naturalearth/50m/physical/ne_50m_land.zip
Terms: https://www.naturalearthdata.com/about/terms-of-use/
No country borders are used: this is a geographic locator, not an ancient polity map.
"""

from pathlib import Path
import struct
import sys
from zipfile import ZipFile


def clip(points, axis, boundary, keep_greater):
    result = []
    if not points:
        return result
    previous = points[-1]
    for current in points:
        inside = (current[axis] >= boundary) if keep_greater else (current[axis] <= boundary)
        previous_inside = (previous[axis] >= boundary) if keep_greater else (previous[axis] <= boundary)
        if inside != previous_inside:
            fraction = (boundary - previous[axis]) / (current[axis] - previous[axis])
            result.append(tuple(previous[i] + fraction * (current[i] - previous[i]) for i in range(2)))
        if inside:
            result.append(current)
        previous = current
    return result


with ZipFile(sys.argv[1]) as archive:
    data = archive.read("ne_50m_land.shp")

paths = []
offset = 100
while offset < len(data):
    length = struct.unpack_from(">i", data, offset + 4)[0] * 2
    record = data[offset + 8:offset + 8 + length]
    offset += 8 + length
    if struct.unpack_from("<i", record)[0] != 5:
        continue
    xmin, ymin, xmax, ymax = struct.unpack_from("<4d", record, 4)
    if xmax < 17.3 or xmin > 31.2 or ymax < 34.3 or ymin > 42.7:
        continue
    part_count, point_count = struct.unpack_from("<2i", record, 36)
    parts = list(struct.unpack_from(f"<{part_count}i", record, 44)) + [point_count]
    coordinates = list(struct.iter_unpack("<2d", record[44 + part_count * 4:44 + part_count * 4 + point_count * 16]))
    for start, end in zip(parts, parts[1:]):
        points = coordinates[start:end]
        for axis, boundary, greater in [(0, 17.3, True), (0, 31.2, False), (1, 34.3, True), (1, 42.7, False)]:
            points = clip(points, axis, boundary, greater)
        if len(points) < 3:
            continue
        projected = [(round(34 + (lon - 18.5) * 37 * .78, 1), round(88 + (42.7 - lat) * 37, 1)) for lon, lat in points]
        paths.append("M" + "L".join(f"{x},{y}" for x, y in projected) + "Z")

output = Path(__file__).resolve().parents[2] / "src/features/course-lesson/greece-coastline.ts"
output.write_text(
    "// Generated by scripts/assets/generate-greece-map.py from Natural Earth 1:50m land.\n"
    "// Public domain: https://www.naturalearthdata.com/about/terms-of-use/\n"
    'export const GREECE_COASTLINE = "' + "".join(paths) + '";\n', encoding="utf-8"
)
print(f"Generated {len(paths)} rings, {output.stat().st_size:,} bytes")
